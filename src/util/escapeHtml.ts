/** Escapes HTML-significant characters — shared by every place that drops pack-sourced text into a Foundry HTML field (journal pages, chat messages). */
export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
